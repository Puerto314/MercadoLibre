		bVolverM.setForeground(Color.decode("#FFFFFF"));
		bVolverM.setFocusPainted(false);
		bVolverM.setBorderPainted(false);
		add(bVolverM);

		// boton vendedor
		bModoVendedorM = new JButton("MODO VENDEDOR");
